function gen_mcu_tables()
% EMB-01（2026-09-21）：由 mcu_export.mat 生成裸机固件所需的转移核表头文件，
% 并核对 movmedian 的 NaN 语义（供 C 版 median3 对齐）。
%
% 输入：results/mcu_export.mat（由 exp_export_mcu.m 生成）
% 输出：fw/mcu_tables.h —— MCU_A[K]（行归一化常数的对数：a[i] = -log(Σ_j exp(-(i-j)^2/(2σ^2)))）
%       results/table_check.txt —— 语义核对记录
%
% 说明：转移核可分离：logT(i,j) = g[|i-j|] + a[i]，g[d] = -d^2/(2σ^2)，σ=2（论文口径）。
here = fileparts(mfilename('fullpath'));
outdir = fullfile(here, 'results');
fwdir = fullfile(here, 'fw');
if ~exist(fwdir, 'dir'), mkdir(fwdir); end
S = load(fullfile(outdir, 'mcu_export.mat'), 'est', 'es_default', 'es_omitnan', 'K', 'nWin');

K = S.K; sig = 2;
d = (1:K)' - (1:K);
Sr = sum(exp(-(d.^2) / (2 * sig^2)), 2);   % 行和（含整行归一化）
a = -log(Sr);                               % a[i] = -log(S_i)

fw = fopen(fullfile(outdir, 'table_check.txt'), 'w');
fprintf(fw, 'K=%d sigma=%g\n', K, sig);
fprintf(fw, 'est(1:6):        '); fprintf(fw, '%.6g ', S.est(1:6)); fprintf(fw, '\n');
fprintf(fw, 'es_default(1:6): '); fprintf(fw, '%.6g ', S.es_default(1:6)); fprintf(fw, '\n');
fprintf(fw, 'es_omitnan(1:6): '); fprintf(fw, '%.6g ', S.es_omitnan(1:6)); fprintf(fw, '\n');
fprintf(fw, 'a(1:4) = %.9g %.9g %.9g %.9g\n', a(1:4));
fprintf(fw, 'a(end-3:end) = %.9g %.9g %.9g %.9g\n', a(end-3:end));
fclose(fw);

fh = fopen(fullfile(fwdir, 'mcu_tables.h'), 'w');
fprintf(fh, '/* auto-generated by gen_mcu_tables.m (EMB-01, 2026-09-21)\n');
fprintf(fh, ' * transition kernel row-normalisation constants for sigma = %g, K = %d\n */\n', sig, K);
fprintf(fh, '#ifndef MCU_TABLES_H\n#define MCU_TABLES_H\n\n');
fprintf(fh, '#define MCU_K %d\n#define MCU_SIGMA %gf\n#define MCU_D 3\n\n', K, sig);
fprintf(fh, 'static const float MCU_A[MCU_K] = {\n');
for i = 1:K
    if mod(i - 1, 6) == 0, fprintf(fh, '  '); end
    fprintf(fh, '%.9gf,', a(i));
    if mod(i, 6) == 0, fprintf(fh, '\n'); end
end
fprintf(fh, '\n};\n\n#endif\n');
fclose(fh);
fprintf('mcu_tables.h written (%d entries)\n', K);
end
